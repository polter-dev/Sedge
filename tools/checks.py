"""Checks that the generated data and the question bank are fit to measure with.

Run from tools/:  uv run python checks.py
It regenerates every persona in memory and checks, printing only counts and match/mismatch:
  1. answer-key invariants for every persona (also run by fake_gen.py before it writes),
  2. each data file against tools/data/manifest.json and the regenerated bytes,
  3. merchant names shared between the validation personas and the dev/test ones,
  4. the validation questions' type mix against the dev questions'.
Held-out personas (jordan, elena) are never printed: their checks report counts only.
"""
import contextlib
import csv
import hashlib
import io
import platform
import sys
from collections import Counter
from pathlib import Path

import fake_gen

TOOLS = Path(__file__).resolve().parent
DATA = TOOLS / "data"
MANIFEST = DATA / "manifest.json"
QUESTIONS = TOOLS / "eval" / "questions.csv"

HELD_OUT = ("jordan", "elena")
VALIDATION = ("nia", "otis")
KINDS = {"spending", "income", "transfer", "card_payment"}
RECURRING = {"none", "weekly", "biweekly", "twice_monthly", "monthly", "quarterly", "yearly"}
INCOME_TYPES = {"wages", "household_contribution"}
INVARIANTS = ["records", "labels", "merchant", "income_sign", "pairs", "refunds", "card_payments", "card_balance", "balances", "totals"]
MIX_TOLERANCE = 0.05  # each question type's share may differ from dev's by 5 points


def cents(amount):
  return round(amount * 100)


def sha256(text):
  return hashlib.sha256(text.encode()).hexdigest()


def regenerate():
  """Every persona's files, built in memory with the generator's printing silenced (it shows balances)."""
  with contextlib.redirect_stdout(io.StringIO()):
    return fake_gen.build_all()


def invariant_failures(person, files):
  """How many records break each invariant; an empty Counter means every invariant holds."""
  data, key, bank = files["transactions"], files["answer_key"], files["accounts"]
  labels = {e["transaction_id"]: e for e in key["transactions"]}
  tx = {t["transaction_id"]: t for t in data}
  types = {a["account_id"]: a["type"] for a in person["accounts"]}
  failures = Counter({name: 0 for name in INVARIANTS})

  # Every posted record has exactly one label, in the same order, and nothing pending is left.
  if [t["transaction_id"] for t in data] != [e["transaction_id"] for e in key["transactions"]] or len(tx) != len(data):
    failures["records"] += 1
  failures["records"] += sum(t["pending"] for t in data)

  for t in data:
    e = labels.get(t["transaction_id"], {})
    kind = e.get("kind")
    # income_type is optional, and only income may carry it
    if kind not in KINDS or e.get("recurring") not in RECURRING or (
        "income_type" in e and (kind != "income" or e["income_type"] not in INCOME_TYPES)):
      failures["labels"] += 1
    # Money moved between the person's own accounts has no store; everything else has one.
    if (kind in ("transfer", "card_payment")) != (e.get("true_merchant") is None):
      failures["merchant"] += 1
    if kind == "income" and t["amount"] >= 0:
      failures["income_sign"] += 1
    if kind in ("transfer", "card_payment"):
      other = tx.get(e.get("linked_transaction_id"))
      other_label = labels.get(other["transaction_id"], {}) if other else {}
      touches_card = other and "credit" in (types[t["account_id"]], types[other["account_id"]])
      if (not other or other_label.get("linked_transaction_id") != t["transaction_id"] or other_label.get("kind") != kind
          or other["account_id"] == t["account_id"] or cents(t["amount"]) + cents(other["amount"]) != 0
          or bool(touches_card) != (kind == "card_payment")):
        failures["pairs"] += 1
    if kind == "spending" and t["amount"] < 0:
      original = tx.get(e.get("linked_transaction_id"))
      if (not original or cents(original["amount"]) != -cents(t["amount"]) or original["date"] >= t["date"]
          or labels[original["transaction_id"]]["true_merchant"] != e["true_merchant"]):
        failures["refunds"] += 1

  # Each card is paid in full for the previous month's net spending, and owes June's at the end.
  for card in (a["account_id"] for a in person["accounts"] if a["type"] == "credit"):
    def on_card(kind, month):
      return sum(cents(t["amount"]) for t in data
                 if t["account_id"] == card and labels[t["transaction_id"]]["kind"] == kind and t["date"][5:7] == f"{month:02d}")
    for month in range(2, 7):
      spent = on_card("spending", month - 1)
      if -on_card("card_payment", month) != max(spent, 0):
        failures["card_payments"] += 1
    ending = next(a["ending_balance"] for a in key["accounts"] if a["account_id"] == card)
    if cents(ending) != on_card("spending", 6):
      failures["card_balance"] += 1

  # Balances rebuilt from the postings match both the answer key and the bank-facing accounts file.
  current = {a["account_id"]: a["balances"]["current"] for a in bank}
  for account in key["accounts"]:
    sign = 1 if types[account["account_id"]] == "credit" else -1
    rebuilt = cents(account["starting_balance"]) + sign * sum(cents(t["amount"]) for t in data if t["account_id"] == account["account_id"])
    if not rebuilt == cents(account["ending_balance"]) == cents(current[account["account_id"]]):
      failures["balances"] += 1

  income = -sum(cents(t["amount"]) for t in data if labels[t["transaction_id"]]["kind"] == "income")
  spending = sum(cents(t["amount"]) for t in data if labels[t["transaction_id"]]["kind"] == "spending")
  if (income, spending) != (cents(key["totals"]["income"]), cents(key["totals"]["spending"])):
    failures["totals"] += 1
  return failures



def report_invariants(built):
  """Print 'k/K invariants pass' per persona; only dev and validation also name what failed. Returns the failure count."""
  total = 0
  for name, files in built.items():
    failures = invariant_failures(fake_gen.PERSONAS[name], files)
    broken = [inv for inv in INVARIANTS if failures[inv]]
    total += len(broken)
    line = f"{name}: {len(INVARIANTS) - len(broken)}/{len(INVARIANTS)} invariants pass"
    if broken and name not in HELD_OUT:
      line += f" (failed: {', '.join(broken)})"
    print(line)
  return total


def manifest(built):
  """What it takes to rebuild the data: seeds, the generator's and lock file's hashes, and every file's hash."""
  seeds = {name: person.get("seed", 42) for name, person in fake_gen.PERSONAS.items()}
  return {
    "note": "Personas without their own seed share one random stream seeded 42, in PERSONAS order.",
    "python": platform.python_version(),
    "generator_sha256": hashlib.sha256((TOOLS / "fake_gen.py").read_bytes()).hexdigest(),
    "uv_lock_sha256": hashlib.sha256((TOOLS / "uv.lock").read_bytes()).hexdigest(),
    "seeds": seeds,
    "files": {f"{name}/{file}.json": sha256(fake_gen.serialize(contents))
              for name, files in built.items() for file, contents in files.items()},
  }


def write_manifest(built):
  MANIFEST.write_text(fake_gen.serialize(manifest(built)))


def file_mismatches(built, recorded):
  """Data files whose bytes on disk differ from the regenerated bytes or from the manifest, as (path, ok) pairs."""
  fresh = manifest(built)["files"]
  results = []
  for path in sorted(set(fresh) | set(recorded["files"])):
    on_disk = DATA / path
    disk_hash = hashlib.sha256(on_disk.read_bytes()).hexdigest() if on_disk.exists() else None
    results.append((path, disk_hash == fresh.get(path) == recorded["files"].get(path)))
  return results


def merchant_names(person):
  """Every store or payer name in a persona's config, with its statement spellings, upper-cased."""
  names = set()
  def walk(value):
    if isinstance(value, dict):
      for k, v in value.items():
        if k in ("name", "true_merchant") and isinstance(v, str):
          names.add(v)
        elif k not in ("accounts", "owners"):  # account names like "Checking" aren't stores
          walk(v)
    elif isinstance(value, list):
      for v in value:
        walk(v)
  walk(person)
  names |= {s for n in list(names) for s in fake_gen.SPELLINGS.get(n, [])}
  return {n.upper() for n in names}


def shared_merchants():
  """How many validation merchant names also appear in a dev or test persona's config."""
  mine, others = set(), set()
  for name, person in fake_gen.PERSONAS.items():
    (mine if name in VALIDATION else others).update(merchant_names(person))
  return len(mine & others)


def type_mix(path=QUESTIONS):
  """Question counts per type for the dev and validation splits."""
  with open(path, newline="") as f:
    rows = [r for r in csv.DictReader(f) if r["split"] in ("dev", "validation")]
  return {split: Counter(r["type"] for r in rows if r["split"] == split) for split in ("dev", "validation")}


def mix_off(mix):
  """Types whose share of the validation questions is more than MIX_TOLERANCE from dev's."""
  dev, val = mix["dev"], mix["validation"]
  if not val:
    return sorted(dev)
  return sorted(t for t in set(dev) | set(val)
                if abs(dev[t] / sum(dev.values()) - val[t] / sum(val.values())) > MIX_TOLERANCE)


def main():
  import json
  built = regenerate()
  problems = report_invariants(built)

  recorded = json.loads(MANIFEST.read_text())
  generator_ok = recorded["generator_sha256"] == manifest(built)["generator_sha256"]
  print(f"generator: {'match' if generator_ok else 'mismatch'}")
  for path, ok in file_mismatches(built, recorded):
    print(f"{path}: {'match' if ok else 'mismatch'}")
    problems += not ok
  problems += not generator_ok

  shared = shared_merchants()
  print(f"merchant names shared between validation and dev/test: {shared}")
  problems += shared

  mix = type_mix()
  for t in sorted(set(mix["dev"]) | set(mix["validation"])):
    print(f"  {t}: dev {mix['dev'][t]}, validation {mix['validation'][t]}")
  off = mix_off(mix)
  print(f"question types off dev's mix by more than {MIX_TOLERANCE:.0%}: {len(off)}{' (' + ', '.join(off) + ')' if off else ''}")
  problems += len(off)
  return 1 if problems else 0


if __name__ == "__main__":
  sys.exit(main())
